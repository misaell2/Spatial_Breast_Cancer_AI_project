"""
Milestone 2.5: Preliminary marker-score annotation of Leiden clusters.

Purpose
-------
This script adds a first-pass biological interpretation layer to the
unsupervised Leiden clusters generated in Milestone 2.

At this stage, Leiden clusters are only computational labels such as:
    0, 1, 2, ..., 11

This script helps convert those cluster IDs into provisional biological
labels such as:
    Tumor epithelial
    Stromal/CAF
    Immune-enriched
    Myeloid/macrophage
    Endothelial/vascular
    Proliferative

Important
---------
These are preliminary labels only.

They are based on known marker-gene signature scores, not formal
cluster-specific differential expression. The more rigorous annotation step is
performed later in:

    src/analysis/03_marker_gene_analysis.py

Analysis choices and alternatives
---------------------------------
This script uses Scanpy's `sc.tl.score_genes`, which computes a relative
signature score for each spot based on a marker gene list.

Alternative approaches that could be explored later include:
    - AUCell-style gene set activity scoring
    - ssGSEA / GSVA-style pathway scoring
    - decoupler-based pathway or transcription factor activity scoring
    - Cell-type deconvolution using a single-cell RNA-seq reference
    - Manual pathologist-informed annotation from H&E morphology
    - Spatial neighborhood enrichment using Squidpy
"""

