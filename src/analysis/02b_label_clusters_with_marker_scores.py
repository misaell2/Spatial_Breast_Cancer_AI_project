#   - Markers can overlap across biological states.
#   - Visium spots can contain mixtures of cell types.
#   - Scores should be interpreted as enrichment-like signals, not pure
#     cell-type proportions.
#
# Possible future improvements:
#   - Expand these marker sets using curated sources such as MSigDB,
#     PanglaoDB, CellMarker, or Azimuth references.
#   - Use a breast cancer single-cell reference to estimate cell-type
#     proportions per Visium spot.
#   - Add separate signatures for CAF subtypes, macrophage polarization,
